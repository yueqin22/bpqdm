/* ---------------------------------------------------------------------------
 * Trace and knobs
 * ------------------------------------------------------------------------ */

struct PROT_ENT protTrace[PROT_N];
Uint32          protTraceN;
Uint32          protTraceHash;
Uint16          mockUpDownRc;

#define FNV_OFFSET 2166136261UL
#define FNV_PRIME  16777619UL

static void log_call(Uint16 which, Uint16 a0, Uint16 a1, Uint16 a2, Uint16 a3)
{
    if (protTraceN < PROT_N)
    {
        struct PROT_ENT *e = &protTrace[protTraceN];
        e->which = which;
        e->a0 = a0;
        e->a1 = a1;
        e->a2 = a2;
        e->a3 = a3;
    }

    protTraceHash ^= (Uint32)which;  protTraceHash *= FNV_PRIME;
    protTraceHash ^= (Uint32)a0;     protTraceHash *= FNV_PRIME;
    protTraceHash ^= (Uint32)a1;     protTraceHash *= FNV_PRIME;
    protTraceHash ^= (Uint32)a2;     protTraceHash *= FNV_PRIME;
    protTraceHash ^= (Uint32)a3;     protTraceHash *= FNV_PRIME;

    protTraceN++;
}

void mockReset(void)
{
    Uint32 i;

    protTraceN    = 0;
    protTraceHash = FNV_OFFSET;

    for (i = 0; i < PROT_N; i++)
    {
        protTrace[i].which = 0;
        protTrace[i].a0 = protTrace[i].a1 = 0;
        protTrace[i].a2 = protTrace[i].a3 = 0;
    }
}

/* ---------------------------------------------------------------------------
 * The two stubs
 * ------------------------------------------------------------------------ */

/* On success the stub perturbs *data by +1 before returning.  That is not a
 * claim about what the real ModifyFunccodeUpDown does -- it is a deliberate,
 * driver-independent disturbance so that "the module forwarded the value it got
 * back" and "the module forwarded the value it passed in" are distinguishable.
 * Without it the two are the same word and the loop's data flow is untested.
 *
 * `delta` is logged rather than used: the module always passes 0, and logging it
 * is what makes "a rewrite that passes something else" visible.
 *
 * The stub never touches funcCode, so the driver's funcCode comparison proves
 * the module itself treats the union as read-only here. */
Uint16 ModifyFunccodeUpDown(Uint16 index, Uint16 *data, int16 delta)
{
    Uint16 v = data ? *data : 0;
    Uint16 rc = mockUpDownRc;

    if (rc == COMM_ERR_NONE && data)
    {
        *data = (Uint16)(v + 1);
    }

    log_call(PROT_UPDOWN, index, v, (Uint16)delta, rc);
    return rc;
}

Uint16 ModifyFunccodeEnter(Uint16 index, Uint16 data)
{
    log_call(PROT_ENTER, index, data, 0, 0);
    return COMM_ERR_NONE;
}
