/* Shared stand-ins for the f_profibus differential test.
 *
 * f_profibus.c reaches outside itself in two ways.
 *
 *   * 21 data objects it reads (and, for nine of them, writes).  All 21 are
 *     declared extern in project headers and defined in other .c files.  Those
 *     files cannot be linked here -- f_comm.c is the SCIA register programmer
 *     and f_funcCode.c does not compile on MSVC at all (see below) -- and none
 *     of the 21 is needed: they are plain data, so a definition here is what the
 *     target starts with (the target's .bss is zeroed by the boot code).
 *
 *     Two of them are easy to get wrong and are called out:
 *
 *       frq and frqAim are `int32`, not Uint16 (f_frqSrc.h:71 and :77).
 *         setDPStatusInfo compares them (`frq == frqAim`) and both operands are
 *         32-bit signed, so defining them 16 bits wide would silently change
 *         which comparison the host performs.  Note that ProfibusSendDataDeal
 *         declares a *local* `Uint16 frq` that shadows the global -- so the
 *         global frq is read in exactly one place, and it is not that one.
 *
 *       sendFrame / rcvFrame are widened from 35 to FRAME_N words; see
 *         mock_profibus.h for why (the module's own PPO5 frame length reaches
 *         index 35 in the real 35-word array).
 *
 *   * two functions it calls, ModifyFunccodeUpDown and ModifyFunccodeEnter, both
 *     from the PZD loop.  Neither has an effect the driver could see -- the
 *     module passes a *local* index and never stores it -- so both are stubs
 *     that log their arguments.  See mock_profibus.h for the trace shape.
 *
 * ---- funcCodeGradeSum ----
 *
 * GetGradeIndex(group, grade) is a macro that expands to
 * `funcCodeGradeSum[group] + grade` (f_funcCode.h:17), and f_profibus uses it
 * twice per PZD iteration: once for the write index, once for the read index.
 * The array itself is owned by src/function/f_funcCode.c, which cannot be linked
 * in: it also defines funcCode (which this mock owns, shared by both sides), and
 * its static initialisers are `GetCodeIndex(funcCode.group.fX[0])` -- a
 * difference of two address constants, which MSVC rejects (C2099).
 *
 * So the table is rebuilt from an equivalent *constant* formulation, in
 * grade_tables.inc, generated by tools/difftest/gen_plc_grade_tables.py from the
 * header's own member list and the .c file's own initialiser list.  The same
 * generated file is used by the f_plc case; the derivation and the two
 * rejected formulations are documented in that script and in cases/f_plc.
 *
 * Only funcCodeGradeSum is needed here -- f_profibus never references
 * funcCodeGradeAll, which is why this mock is one table short of f_plc's.
 *
 * The table is load-bearing rather than decorative: indexWrite and indexRead
 * are computed from it, indexWrite is handed to the stubs above, and indexRead
 * is used to read funcCode.all[].  The driver re-derives all 83 entries at run
 * time from the module's own GetCodeIndex and compares, so "sizeof arithmetic
 * equals GetCodeIndex" is tested rather than assumed.
 */

